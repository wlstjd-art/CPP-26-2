/*==========================================================
 [배울 점] #define 상수와 2차원 배열로 표 만들기
 --------------------------------------------------------
  - #define width 9 — 컴파일 전에 기호를 값으로 치환. 크기 변경을 한 곳에서
  - table[r][c] = (r+1)*(c+1) — 인덱스는 0부터, 구구단은 1부터: 오프셋(+1) 변환의 좋은 예
  - 계산으로 채우기와 출력을 따로 나누는 2단계 구조
==========================================================*/
#include <iostream>
// 학습: 전처리 단계의 텍스트 치환. 크기 두곳를 한 번에 바꾸는 방식 (C에서 그대로 넘어온 방식)
#define width 9
#define height 3


int main(){
    int table[height][width];
    int r,c;

    for(r=0;r<height;r++){
        for(c=0;c<width;c++){
            // 학습: 0-based 인덱스와 1-based 실제 값을 맞추는 +1 오프셋
            table[r][c] = (r +1)*(c+1);
        }
    }
    for(r=0;r<height;r++){
        for(c=0;c<width;c++){
            std::cout <<table[r][c] <<" ";

        }
        std::cout <<'\n';
    }




}