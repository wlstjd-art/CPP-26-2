/*==========================================================
 [배울 점] while문으로 구구단 — 루프 변수의 생애
 --------------------------------------------------------
  - i를 밖에서 1로 초기화하고, 반복문 안에서 i++ — 이 두 위치를 잊으면 무한 루프
  - for로도 1줄에 쓸 수 있지만, 상태가 복잡한 계산은 while이 더 잘 읽힌다
  - n*i처럼 매 반복마다 계산에 쓰일 입력(n)은 루프 밖에서 한 번만 받는 구조
==========================================================*/
#include <iostream>

int main(){

    int n;
    int i = 1;

    std::cout <<"Enter a: ";
    std::cin >> n;
    // 학습: 조건 검사 후 본문 실행. i++를 본문 안에 넣는 걸 잊으면 끝이 없다
    while(i <=9){
        std::cout << n << "*"<<i<<"="<<n*i<<'\n';
        i++;
    }


    return 0;
}