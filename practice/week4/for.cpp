/*==========================================================
 [배울 점] for문의 3요소 — 초기화 / 조건 / 갱신
 --------------------------------------------------------
  - for(초기화; 조건; 갱신) 은 한 줄에 루프의 생애 전체를 담는 구조
  - for 안에서 선언한 int i 는 루프 안에서만 보인다 (스코프) — 루프 밖에서 쓰면 에러
  - i<=7 과 i<8 의 차이를 생각해보기 (경계값 실수 예방 훈련)
==========================================================*/
#include <iostream>

int main(){
    // 학습: 여기서 선언한 i는 루프가 끝나면 사라진다 (블록 스코프)
    for(int i = 0; i <= 7 ; i++){
        std::cout << "hello"<<'\n';
    }
    return 0;
}