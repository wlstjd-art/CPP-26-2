/*==========================================================
 [배울 점] do-while = 무조건 한 번은 실행한다
 --------------------------------------------------------
  - while은 조건부터 봐서 한 번도 안 돌 수 있지만, do-while은 먼저 실행하고 조건을 본다
  - '최소 한 번은 물어봐야 하는' 입력 루프에 제격 — 여기도 처음부터 한 줄을 입력받는다
  - getline(cin, str) 은 cin>>와 달리 공백을 포함한 한 줄 전체를 읽는다
==========================================================*/
#include <iostream>
#include <string>

int main(){
    std::string str;

    // 학습: 먼저 실행하고 나중에 조건 검사 → 최소 1회 실행 보장
    do{
        std::cout <<"Enter line ";
        // 학습: 한 줄 전체(공백 포함) 읽기. quit을 입력할 때까지 반복
        getline(std::cin,str);
        std::cout <<"Your line is "<< str <<'\n';

        
    }while(str !="quit");

    return 0;
}