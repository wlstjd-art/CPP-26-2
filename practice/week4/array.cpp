/*==========================================================
 [배울 점] 배열의 기본 — 크기 고정, 0부터 시작, 인덱스로 접근
 --------------------------------------------------------
  - int sales[5] 선언 시 크기가 확정. 이후에 크기를 바꿀 수 없다 (크기가 바뀌어야 하면 vector — week9)
  - sales[3]=4 처럼 인덱스로 개별 원소를 읽거나 바꾼다
  - for문 + 인덱스로 배열 전체를 순회하는 패턴
==========================================================*/
#include <iostream>

int main(){

    // 학습: 크기가 고정된 배열. 이후 확장이 안 되는 게 C 배열의 한계
    int sales[5] = {100,200,300,400,500};

    for(int i = 0; i < 5; i++){
        std::cout <<sales[i]<<'\n';
    }
    // 학습: 인덱스는 0부터. 4번째 원소는 sales[3] — off-by-one 주의
    sales[3]=4;

    for(int i = 0; i < 5; i++){
        std::cout <<sales[i]<<'\n';
    }


    return 0;
}