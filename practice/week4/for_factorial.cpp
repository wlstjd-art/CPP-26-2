/*==========================================================
 [배울 점] 누산기 패턴 + 실제 버그를 찾는 훈련
 --------------------------------------------------------
  - 팩토리얼 = 곱을 쌓는 누산기. 초기값은 1 (곱셈의 항등원). 0으로 시작하면 전부 0이 된다
  - 팩토리얼은 금방 커지므로 int 대신 long을 고른 판단이 좋음
  - ⚠ 이 코드에는 진짜 버그가 있다: i를 0부터 시작시켜서 항상 0이 출력됨 — 직접 고쳐보자
==========================================================*/
#include <iostream>

int main(){

    // 학습: 누산기는 1 시작 — 곱셈에서 1은 '아무것도 안 한 것과 같은 값'(항등원)
    long fact = 1;
    int n;

    std::cout <<"Enter a num: ";
    std::cin >> n;
    
    // ⚠ 버그: i=0에서 fact*0=0이 되어 결과가 항상 0! for(int i=1; i<=n; i++)이 정답
    for(int i = 0; i <= n; i++){
        fact = fact * i;
    }

    std::cout <<"!" <<n<<"is "<<fact;

    return 0;
}