/*==========================================================
 [배울 점] vector는 '같은 값'이면 같다고 말한다 — 연산자 오버로딩
 --------------------------------------------------------
  - vector<int> v2(v1); 복사 생성 — 원소 전체를 복사해 별도 객체를 만든다
  - v1 == v2 는 '같은 물건?'(C의 포인터 비교)이 아니라 '내용이 같은가?' — vector가 == 를 오버로딩해놨기 때문
  - logic_and_string.cpp의 string 비교와 같은 원리: 타입이 연산자의 의미를 정의한다
==========================================================*/
#include <vector>
#include <iostream>
using namespace std;

int main(void){
    vector <int> v1 {1,2,3,4,5};
    // 학습: 복사 생성자 — v1의 모든 원소를 복사한 독립 객체
    vector <int> v2(v1);

    // 학습: 주소가 아니라 내용 비교. 표준 라이브러리가 미리 오버로딩해준 결과
    if(v1 == v2){
        cout << "같은 벡터입니다!" << endl;
    }
    return 0;
}