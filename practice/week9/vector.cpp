/*==========================================================
 [배울 점] vector 리스트 초기화의 두 가지 시점
 --------------------------------------------------------
  - vector<int> fib {0,2,3,...} 생성과 동시에 리스트 초기화
  - 비워놓고 fib = {1,2,3,4}; 나중에 대입하는 것도 가능
  - 배열과 달리 크기 숫자를 안 적는다 — 요소 개수가 곧 크기가 된다
==========================================================*/
#include <vector>
#include <iostream>
using namespace std;

int main(void){

    //vector <int> fibonacci;
    //fibonacci = {1,2,3,4}; 도가능!
    // 학습: C++11 리스트 초기화 — 위 주석처럼 나중에 = {}로도 채울 수 있다
    vector<int> fibona {0,2,3,4,1214,3};
    //새로운초기화방법!


    for(auto number : fibona){
        cout << number << ' ';
    }
    cout << endl;
    return 0;
}