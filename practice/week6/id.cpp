/*==========================================================
 [배울 점] continue로 문자 걸러내기 + string 순회
 --------------------------------------------------------
  - string도 문자 컨테이너 — for(char c : s) 로 한 글자씩 순회할 수 있다
  - continue 는 남은 본문을 건너뛰고 다음 반복으로 — '-'를 버리는 필터가 이렇게 간단하다
  - '특정 문자 제거'를 컴퓨터가 잘하는 단순 작업으로 분해하는 사고법
==========================================================*/
#include <iostream>
#include <string>
using namespace std;

int main()
{
    string s;
    cout << "주민번호를 입력하세요: ";
    cin >> s;

    cout << "-가 제거된 주민번호: ";
    // 학습: string은 char의 묶음 — 범위 기반 for로 글자 단위 순회 가능
    for (char c : s)
    {
        if(c == '-')
        {
            // 학습: 이 줄 이후는 건너뛰고 다음 글자로 → '-'가 화면에 안 나오는 원리
            continue;
        }
        cout << c;
    }
    cout << endl;

    return 0;
}