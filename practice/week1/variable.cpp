/*==========================================================
 [배울 점] 변수 선언과 통일 초기화 {} (C++11)
 --------------------------------------------------------
  - int a{100}; 중괄호 초기화는 자료 손실(double 3.5 -> int 같은)이 있으면 컴파일 에러로 막아준다 — C의 int a=3.5는 조용히 잘린다
  - int / string / bool / char 기본 타입 4종을 한눈에 보여주는 예제
  - bool은 화면에 true/false가 아니라 1/0으로 찍힌다는 점도 함께 배운다
==========================================================*/
#include <iostream>

int main(){

    //int a = 100;
    // 학습: 통일 초기화 {} — C++11 권장 방식, 값 손실 시 컴파일이 거부된다
    int  a{100};
    std::string s{"hello"};
    // 학습: bool을 cout으로 찍으면 1이 나온다 (true라는 문자열이 아님)
    bool student{true};
    char grade{'A'};


    std::cout <<a<<'\n';
    std::cout <<s<<'\n';
    std::cout <<student<<'\n';
    std::cout <<grade<<'\n';



    return 0;
}