/*==========================================================
 [배울 점] 모든 C++ 프로그램의 뼈대
 --------------------------------------------------------
  - iostream = 화면 출력(cout)과 키보드 입력(cin)을 쓰겠다고 포함시키는 헤더
  - main()은 프로그램의 시작점. OS가 main이 반환한 정수를 '종료 코드'로 받는다 (0 = 성공)
  - C의 printf 대신 std::cout << 를 쓴다 — << 가 stream 안으로 값을 밀어넣는 원리
==========================================================*/
#include <iostream>

int main(){

    // 학습: << 로 값을 stream에 밀어넣는 C++ 출력의 출발점
    std::cout << "Hello World!"<<'\n';
    return 0;
}