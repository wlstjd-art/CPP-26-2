/*==========================================================
 [배울 점] 참조(&)로 넘기기 vs 값으로 넘기기 — 이 파일이 최고 예제
 --------------------------------------------------------
  - MakeDouble(Pizza& p): Pizza&라서 함수 안의 p는 '원본 그 자체'. 호출 후 p.size가 진짜 20인치
  - Pizza로 값 넘기기를 하면 복사본만 커지고 원본은 그대로 — 이 한 글자(&)의 차이가 C++의 절반
  - Pizza(int s) : size(s) {} — 초기화 리스트. 생성자 본문 전에 멤버를 초기화하는 관용구
==========================================================*/
#include <iostream>
using namespace std;

class Pizza
{
public:
 int size;
 // 학습: 생성자 초기화 리스트 — 본문 {} 전에 멤버를 직접 초기화, 빠르고 정확
 Pizza(int s) : size(s) {}
};

// 학습: & = 참조. 함수가 '진짜 p'를 고친다. 값으로 하면 복사본만 고침
void MakeDouble(Pizza& p)
{
 p.size *= 2;
}

int main()
{
 Pizza p(10);
 // 학습: 호출 후 main의 p.size가 10에서 20으로. 사이드이펙트의 원리를 눈으로 확인
 MakeDouble(p);
 cout << p.size << "인치 피자" << endl;
 return 0;
}
