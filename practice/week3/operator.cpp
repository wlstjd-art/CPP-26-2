/*==========================================================
 [배울 점] 선치입 ++x vs 후치입 x++ — 출력 시점이 다르다
 --------------------------------------------------------
  - ++x : 먼저 올리고 그 값을 쓴다 -> 2 출력
  - x++ : 현재 값을 먼저 쓰고 올린다 -> 2 출력 후 3이 됨
  - 최종 x는 3. for문의 i++에도 숨어 있는, 면접 단골 개념
==========================================================*/
#include <iostream>

int main(){

    int x = 1;

    //std::cout <<x++<<'\n';
    // 학습: 선치입 — 먼저 2로 올린 다음 출력
    std::cout <<++x<<'\n';
    // 학습: 후치입 — 지금 값(2)을 먼저 출력하고 나서 3으로 증가
    std::cout <<x++<<'\n';

    std::cout <<x<<'\n';



    return 0;
}