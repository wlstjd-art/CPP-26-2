/*==========================================================
 [배울 점] 숫자는 문자열에 바로 못 붙인다 — std::to_string
 --------------------------------------------------------
  - s1 + 10 은 컴파일 에러다. 반드시 std::to_string(10)으로 string으로 바꾼 뒤 붙여야 한다
  - + 를 여러 번 이어서 'apple' + ' ' + '10'처럼 조립하는 패턴
==========================================================*/
#include <iostream>
#include<string>

int main(){


    std::string s1 = "appleA";
    std::string s2;

    // 학습: to_string이 int -> string 변환. 텍스트+숫자 출력의 접착제
    s2 = s1 + " "+ std::to_string(10);
    std::cout <<s2  <<'\n';


    return 0;
}
