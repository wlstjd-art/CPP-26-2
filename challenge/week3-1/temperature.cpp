/*==========================================================
 [배울 점] 5.0/9.0 — 왜 .0을 붙여야 하는가 (가장 흔한 함정)
 --------------------------------------------------------
  - 5/9 (int/int)는 0이다! int끼리의 나눗셈은 소수점을 버리기 때문
  - 5.0/9.0이라고 써야 double끼리의 나눗셈이 되어 소수점이 살아난다
  - C에서 넘어온 사람이 가장 많이 걸리는 함정 — 화씨->섭씨 공식으로 체득해두자
==========================================================*/
#include <iostream>

int main(){
    double a;
    double b;

    std::cout <<"Enter the temperature in F: ";
    std::cin >>a;

    // 학습: .0을 붙여 double 나눗셈으로 만든다. 여기에 5/9를 썼다면 b는 항상 0
    b= (5.0/9.0)*(a-32);

    std::cout <<"Temperature in fer to cel : "<<b;

    return 0;
}