/*==========================================================
 [배울 점] 나눗셈의 마법 — % 연산자 없이 나머지를 구하는 원리
 --------------------------------------------------------
  - int / int 는 몫만 남는다(버림). '살 수 있는 개수'가 저절로 계산되는 원리
  - 나머지 = 전체금액 - 단위가격 x 개수 (num - num2*a). % 없이도 나머지를 만들 수 있다는 생각
  - cout으로 묻고 cin으로 받는 질문-응답 흐름 = 콘솔 프로그램 기본 템플릿
==========================================================*/
#include <iostream>

int main(){

    int num;
    int num2;
    // 학습: 나머지 = 총액 - 단가 x 개수. 이 아이디어가 곳곳에서 다시 나온다
    std::cout <<"Enter the balance: !!!";
    std::cin >>num;
    std::cout <<"Enter a: ";
    std::cin >>num2;
    // 학습: int / int = 몫만(소수점 버림). 이 한 줄이 프로그램의 핵심 논리
    int a=num/num2;
    
    std::cout <<"You can buy "<<a<<'\n';

    std::cout<<"balance: "<<num - num2* a<<'\n';




    return 0;
}
